import { plotPosition, PLOT_SPACING } from '../shared/world';
import { REWARDS } from '../shared/progression';
import type { PublicProject } from '../shared/types';

export function reward(db:D1Database,key:string,id:string,source:string,xp:number,bricks:number,description:string){
  return db.prepare('INSERT OR IGNORE INTO xp_events(event_key,user_id,source,xp,bricks,description) VALUES(?,?,?,?,?,?,?)')
    .bind(key,id,source,xp,bricks,description).run();
}
export async function projects(db:D1Database,viewer:string|null){
  return (await db.prepare(`SELECT p.*,
    (SELECT COUNT(DISTINCT user_id) FROM project_contributions WHERE project_id=p.id) contributors,
    COALESCE((SELECT SUM(amount) FROM project_contributions WHERE project_id=p.id AND user_id=?),0) myContribution
    FROM public_projects p ORDER BY p.id`).bind(viewer).all<PublicProject>()).results;
}

/** Drain one queued milestone per invocation; unique ledger keys make retries safe.
 * A bounded batch keeps rewards within the free Worker query budget. Further
 * construction generated by XP is queued for the next active request or cron.
 */
export async function processConstruction(db:D1Database){
  const event=await db.prepare('SELECT e.*,u.is_demo FROM construction_events e JOIN users u ON u.id=e.user_id WHERE processed=0 ORDER BY e.rowid LIMIT 1')
    .first<{event_key:string;user_id:string;milestone:number;x:number;z:number;is_demo:number}>();
  if(!event)return [] as string[];
  const source=plotPosition(event.x,event.z);
  const candidates=(await db.prepare('SELECT b.user_id,b.x,b.z FROM buildings b JOIN users u ON u.id=b.user_id WHERE b.user_id<>? AND b.x BETWEEN ? AND ? AND b.z BETWEEN ? AND ? AND u.is_demo=?')
    .bind(event.user_id,event.x-3,event.x+3,event.z-3,event.z+3,event.is_demo).all<{user_id:string;x:number;z:number}>()).results;
  const nearby=candidates.map(b=>({...b,distance:Math.hypot(plotPosition(b.x,b.z).x-source.x,plotPosition(b.x,b.z).z-source.z)}))
    .filter(b=>b.distance<=PLOT_SPACING*3).sort((a,b)=>a.distance-b.distance).slice(0,8);
  await db.batch([...nearby.map(b=>db.prepare(`INSERT OR IGNORE INTO xp_events(event_key,user_id,source,xp,bricks,description) VALUES(?,?, 'construction',?,0,?)`)
    .bind(`${event.event_key}:neighbor:${b.user_id}`,b.user_id,REWARDS.construction,`Nearby construction reached level ${event.milestone}`)),
    db.prepare('UPDATE construction_events SET processed=1 WHERE event_key=?').bind(event.event_key)]);
  return nearby.map(b=>b.user_id);
}
